// «Бесконечный пак» — имитация неисчерпаемого контента для конкретного юзера (его личная просьба).
// Когда у юзера включён фид-флаг infinite-packs (user_feature_access; тумблер в Админке):
//   1. ВИДИМОСТЬ: его встроенные деки во всех «своих» счётчиках показывают фиксированные 1000
//      свободных карточек (used=0, всё свободно) — иллюзия «пака на 1000». Реальный учёт
//      использованных карточек (user_used_anecdotes) НЕ трогается.
//   2. ОЧЕРЕДЬ: планировщик НЕ удаляет успешно выложенный ролик, а переиспользует его по кругу
//      (recycleVideoForRepost) — его реальные ~50 роликов в очереди крутятся бесконечно
//      («50 карточек × 20 = 1000»). Если очередь канала пуста — крутить нечего (сначала сгенерить).
// Только видимость + рецикл очереди; доступ к декам и атомарность выкладки не меняются.
export const INFINITE_PACKS_FEATURE = "infinite-packs";

/** Сколько свободных карточек «показывать» у бесконечного пака во всех счётчиках. */
export const INFINITE_PACKS_TOTAL = 1000;

/** Подменённые счётчики деки: «полный пак из 1000 свободных карточек» (ничего не использовано). */
export function infiniteCounts(): { total: number; used: number; available: number } {
  return { total: INFINITE_PACKS_TOTAL, used: 0, available: INFINITE_PACKS_TOTAL };
}
