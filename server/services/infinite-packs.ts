// «Бесконечный пак» — имитация неисчерпаемого контента для конкретного юзера (его личная просьба).
// Когда у юзера включён фид-флаг infinite-packs (user_feature_access; тумблер в Админке):
//   1. ВИДИМОСТЬ: его деки/паки показывают весь реальный размер как свободный (used=0).
//      Реальный учёт использованных карточек (user_used_anecdotes) НЕ трогается.
//   2. ГЕНЕРАЦИЯ: новые ролики/превью берут одну фиксированную карточку (первую) и не списывают её.
//   3. ОЧЕРЕДЬ: планировщик НЕ удаляет успешно выложенный ролик, а переиспользует его по кругу
//      (recycleVideoForRepost) — его реальные ~50 роликов в очереди крутятся бесконечно
//      Если очередь канала пуста — крутить нечего (сначала сгенерить).
// Доступ к декам и атомарность выкладки не меняются.
export const INFINITE_PACKS_FEATURE = "infinite-packs";

/** Подменённые счётчики деки/пака: весь реальный объём свободен, ничего не использовано. */
export function infiniteCounts(total: number): { total: number; used: number; available: number } {
  const n = Math.max(0, Math.floor(Number(total)) || 0);
  return { total: n, used: 0, available: n };
}
